/**
 * Renders a language's country flag as SVG (not emoji), so it looks the same
 * on Windows, macOS, iOS, and Android alike. Sizes itself relative to the
 * current font-size (1em wide, 0.75em tall — flags are a 4:3 ratio), so
 * dropping it inside an element with a `text-*` class sizes it exactly the
 * way a flag emoji character used to. Renders nothing for an unrecognized code.
 */
export function FlagIcon({ code, className }: { code: string; className?: string }) {
  const uid = useId();
  const country = LANG_TO_COUNTRY[code as FlagLangCode];
  if (!country) return null;
  return (
    <svg
      viewBox="0 0 640 480"
      aria-hidden="true"
      className={cn(
        "inline-block h-[0.75em] w-[1em] shrink-0 rounded-[0.12em] align-[-0.15em] ring-1 ring-black/10",
        className,
      )}
    >
      {country === "gb" && <GbFlag />}
      {country === "de" && <DeFlag />}
      {country === "kr" && <KrFlag uid={uid} />}
      {country === "sa" && <SaFlag uid={uid} />}
    </svg>
  );
}
